import Cocoa
import CryptoKit
import ImageIO
import os.log

/// Local clipboard history. All model/pasteboard access is on main; decoding,
/// thumbnails and atomic persistence share a serial utility queue.
final class ClipboardHistory {
  struct Entry: Codable, Equatable, Identifiable {
    enum Kind: String, Codable { case text, files, image }
    var id = UUID()
    let fingerprint: String
    let kind: Kind
    var text: String?
    var rtf: Data?
    var fileURLs: [String]?
    var imageName: String?
    var pinned = false
    var date = Date()

    var preview: String {
      switch kind {
      case .text: return (text ?? "").split(whereSeparator: \.isNewline).joined(separator: " ")
      case .files:
        let names = (fileURLs ?? []).compactMap { URL(string: $0)?.lastPathComponent }
        return names.joined(separator: ", ")
      case .image: return "Image"
      }
    }
  }

  private struct Snapshot {
    let text: String?
    let rtf: Data?
    let files: [String]
    let image: Data?
  }
  private struct Archive: Codable {
    let version: Int
    let entries: [Entry]
  }

  static let ownType = NSPasteboard.PasteboardType("com.machinespirit.clipboard.paste")
  static let ignoredTypes: Set<NSPasteboard.PasteboardType> = Set(
    [
      "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
      "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
      ownType.rawValue,
    ].map { NSPasteboard.PasteboardType($0) })

  private(set) var entries: [Entry] = []
  private(set) var loaded = false
  var onChange: (() -> Void)?
  var onThumbnail: ((UUID) -> Void)?
  private let pasteboard: NSPasteboard
  let directory: URL
  private let io = DispatchQueue(label: "com.machinespirit.clipboard-storage", qos: .utility)
  private var timer: Timer?
  private var saveWork: DispatchWorkItem?
  private var lastChange: Int
  private var epoch = 0
  private var running = false
  private var pendingImages: [String: Data] = [:]
  private let thumbnails = NSCache<NSUUID, NSImage>()
  private var thumbnailRequests: Set<UUID> = []

  init(pasteboard: NSPasteboard = .general, directory: URL? = nil) {
    self.pasteboard = pasteboard
    self.directory =
      directory
      ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
      .appendingPathComponent("MachineSpirit/clipboard", isDirectory: true)
    lastChange = pasteboard.changeCount
    thumbnails.countLimit = 60
  }

  func start() {
    guard !running else { return }
    running = true
    let version = epoch
    let folder = directory
    io.async { [weak self] in
      var entries: [Entry] = []
      let index = folder.appendingPathComponent("index.json")
      do {
        try FileManager.default.createDirectory(
          at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: folder.path)
        if FileManager.default.fileExists(atPath: index.path) {
          let archive = try JSONDecoder().decode(Archive.self, from: Data(contentsOf: index))
          guard archive.version == 1 else { throw CocoaError(.coderReadCorrupt) }
          // Index paths are data, never arbitrary filesystem paths.
          var seen: Set<String> = []
          entries = archive.entries.filter { entry in
            guard seen.insert(entry.fingerprint).inserted else { return false }
            if entry.kind == .image {
              guard entry.imageName == entry.id.uuidString + ".png" else { return false }
              return FileManager.default.fileExists(
                atPath: folder.appendingPathComponent(entry.imageName!).path)
            }
            return true
          }
        }
      } catch {
        os_log("Clipboard history: could not load index (%{public}@)", error.localizedDescription)
        // Preserve a damaged index for recovery instead of silently overwriting it.
        if FileManager.default.fileExists(atPath: index.path) {
          try? FileManager.default.moveItem(
            at: index, to: folder.appendingPathComponent("index-\(UUID().uuidString).recovery.json")
          )
        }
      }
      let restored = entries
      DispatchQueue.main.async {
        guard let self, self.running else { return }
        if self.epoch == version {
          self.entries = restored
          self.trim()
        }
        self.loaded = true
        self.onChange?()
        self.poll()
      }
    }
    let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    timer.tolerance = 0.25
    RunLoop.main.add(timer, forMode: .common)
    self.timer = timer
  }

  func stop() {
    timer?.invalidate()
    timer = nil
    saveWork?.cancel()
    saveWork = nil
    if loaded { persist() }
    // Finish the last queued atomic write on a deliberate quit.
    io.sync {}
    running = false
    epoch += 1
  }

  /// The idle path only compares an integer. Never request payloads on idle ticks.
  func poll() {
    guard loaded, pasteboard.changeCount != lastChange else { return }
    lastChange = pasteboard.changeCount
    let change = lastChange
    let items = pasteboard.pasteboardItems ?? []
    let types = Set(pasteboard.types ?? []).union(items.flatMap(\.types))
    guard types.isDisjoint(with: Self.ignoredTypes) else { return }
    let files = items.compactMap { item -> String? in
      guard let string = item.string(forType: .fileURL), let url = URL(string: string),
        url.isFileURL
      else { return nil }
      return url.absoluteString
    }
    let text = pasteboard.string(forType: .string)
    let rtf = pasteboard.data(forType: .rtf)
    let image =
      files.isEmpty && rtf == nil
      ? (pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff)) : nil
    // Don't store a mixture if another app changed the clipboard mid-snapshot.
    guard pasteboard.changeCount == change else { return }
    guard (text?.utf8.count ?? 0) <= 8_388_608, (rtf?.count ?? 0) <= 16_777_216,
      (image?.count ?? 0) <= 67_108_864
    else { return }
    let snapshot = Snapshot(text: text, rtf: rtf, files: files, image: image)
    let version = epoch
    io.async { [weak self] in
      guard let prepared = Self.prepare(snapshot) else { return }
      DispatchQueue.main.async {
        guard let self, self.running, self.epoch == version else { return }
        var entry = prepared.0
        if let existing = self.entries.firstIndex(where: { $0.fingerprint == entry.fingerprint }) {
          let previous = self.entries.remove(at: existing)
          entry.id = previous.id
          entry.pinned = previous.pinned
          entry.imageName = previous.imageName
        }
        if let png = prepared.1 {
          let name = entry.id.uuidString + ".png"
          entry.imageName = name
          self.pendingImages[name] = png
        }
        self.entries.insert(entry, at: 0)
        self.trim()
        self.changed()
      }
    }
  }

  private static func prepare(_ snapshot: Snapshot) -> (Entry, Data?)? {
    let kind: Entry.Kind
    var text = snapshot.text
    var png: Data?
    let identity: Data
    if !snapshot.files.isEmpty {
      kind = .files
      identity = (try? JSONEncoder().encode(snapshot.files)) ?? Data()
      text = nil
    } else if let image = snapshot.image {
      guard let source = CGImageSourceCreateWithData(image as CFData, nil),
        let cgImage = CGImageSourceCreateThumbnailAtIndex(
          source, 0,
          [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 2048,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
          ] as CFDictionary)
      else { return nil }
      guard
        let data = NSBitmapImageRep(cgImage: cgImage).representation(using: .png, properties: [:])
      else { return nil }
      kind = .image
      png = data
      identity = data
    } else {
      if text == nil, let rtf = snapshot.rtf {
        text = NSAttributedString(rtf: rtf, documentAttributes: nil)?.string
      }
      guard let value = text, !value.isEmpty else { return nil }
      kind = .text
      identity = Data(value.utf8)
    }
    let fingerprint =
      kind.rawValue + ":" + SHA256.hash(data: identity).map { String(format: "%02x", $0) }.joined()
    let entry = Entry(
      fingerprint: fingerprint, kind: kind, text: text,
      rtf: kind == .text ? snapshot.rtf : nil,
      fileURLs: kind == .files ? snapshot.files : nil)
    return (entry, png)
  }

  private func trim() {
    // Pins are explicit exceptions to both caps; they are never silently evicted.
    while entries.filter({ $0.kind == .image }).count > 50,
      let index = entries.lastIndex(where: { !$0.pinned && $0.kind == .image })
    { entries.remove(at: index) }
    while entries.count > 300, let index = entries.lastIndex(where: { !$0.pinned }) {
      entries.remove(at: index)
    }
    let retained = Set(entries.compactMap(\.imageName))
    pendingImages = pendingImages.filter { retained.contains($0.key) }
  }

  func togglePin(_ id: UUID) {
    guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
    entries[index].pinned.toggle()
    trim()
    changed()
  }

  func delete(_ id: UUID) {
    entries.removeAll { $0.id == id }
    thumbnails.removeObject(forKey: id as NSUUID)
    trim()
    changed()
  }

  func clearUnpinned() {
    epoch += 1  // also discard in-flight captures from before Clear
    entries.removeAll { !$0.pinned }
    trim()
    thumbnails.removeAllObjects()
    changed()
  }

  private func changed() {
    onChange?()
    saveWork?.cancel()
    let work = DispatchWorkItem { [weak self] in self?.persist() }
    saveWork = work
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: work)
  }

  private func persist() {
    let snapshot = entries
    let images = pendingImages
    let folder = directory
    io.async { [weak self] in
      do {
        let fm = FileManager.default
        try fm.createDirectory(
          at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        for (name, data) in images {
          let file = folder.appendingPathComponent(name)
          try data.write(to: file, options: .atomic)
          try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        }
        let index = folder.appendingPathComponent("index.json")
        let data = try JSONEncoder().encode(Archive(version: 1, entries: snapshot))
        try data.write(to: index, options: .atomic)
        try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: index.path)
        let retained = Set(snapshot.compactMap(\.imageName))
        for file in try fm.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)
        where file.pathExtension == "png"
          && UUID(uuidString: file.deletingPathExtension().lastPathComponent) != nil
          && !retained.contains(file.lastPathComponent)
        {
          try fm.removeItem(at: file)
        }
        DispatchQueue.main.async {
          guard let self else { return }
          for (name, data) in images where self.pendingImages[name] == data {
            self.pendingImages.removeValue(forKey: name)
          }
        }
      } catch {
        os_log("Clipboard history: save failed (%{public}@)", error.localizedDescription)
      }
    }
  }

  func thumbnail(for entry: Entry) -> NSImage? {
    if let cached = thumbnails.object(forKey: entry.id as NSUUID) { return cached }
    guard let name = entry.imageName, thumbnailRequests.insert(entry.id).inserted else {
      return nil
    }
    let pending = pendingImages[name]
    let file = directory.appendingPathComponent(name)
    io.async { [weak self] in
      let data = pending ?? (try? Data(contentsOf: file))
      let source = data.flatMap { CGImageSourceCreateWithData($0 as CFData, nil) }
      let image = source.flatMap {
        CGImageSourceCreateThumbnailAtIndex(
          $0, 0,
          [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 96,
            kCGImageSourceCreateThumbnailWithTransform: true,
          ] as CFDictionary)
      }
      DispatchQueue.main.async {
        guard let self else { return }
        self.thumbnailRequests.remove(entry.id)
        if let image {
          self.thumbnails.setObject(
            NSImage(cgImage: image, size: .zero), forKey: entry.id as NSUUID)
          self.onThumbnail?(entry.id)
        }
      }
    }
    return nil
  }

  /// Prepare all representations before replacing the user's current clipboard.
  func copy(_ entry: Entry, completion: @escaping (Bool) -> Void) {
    let pending = entry.imageName.flatMap { pendingImages[$0] }
    let file = entry.imageName.map { directory.appendingPathComponent($0) }
    io.async { [weak self] in
      let png = pending ?? file.flatMap { try? Data(contentsOf: $0) }
      let tiff = png.flatMap { NSBitmapImageRep(data: $0)?.tiffRepresentation }
      DispatchQueue.main.async {
        guard let self else {
          completion(false)
          return
        }
        var items: [NSPasteboardItem] = []
        switch entry.kind {
        case .text:
          let item = NSPasteboardItem()
          item.setString(entry.text ?? "", forType: .string)
          if let rtf = entry.rtf { item.setData(rtf, forType: .rtf) }
          items = [item]
        case .image:
          guard let png else {
            completion(false)
            return
          }
          let item = NSPasteboardItem()
          item.setData(png, forType: .png)
          if let tiff { item.setData(tiff, forType: .tiff) }
          items = [item]
        case .files:
          items = (entry.fileURLs ?? []).map { url in
            let item = NSPasteboardItem()
            item.setString(url, forType: .fileURL)
            return item
          }
        }
        guard !items.isEmpty else {
          completion(false)
          return
        }
        for item in items { item.setString("1", forType: Self.ownType) }
        self.pasteboard.clearContents()
        let success = self.pasteboard.writeObjects(items)
        self.lastChange = self.pasteboard.changeCount
        if success, let index = self.entries.firstIndex(where: { $0.id == entry.id }) {
          var recent = self.entries.remove(at: index)
          recent.date = Date()
          self.entries.insert(recent, at: 0)
          self.changed()
        }
        completion(success)
      }
    }
  }
}
