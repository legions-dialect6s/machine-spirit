import Cocoa
import ImageIO

@main struct ClipboardSmoke {
  static func wait(_ description: String, until condition: () -> Bool) {
    let deadline = Date().addingTimeInterval(10)
    while !condition() && Date() < deadline {
      RunLoop.main.run(until: Date().addingTimeInterval(0.02))
    }
    precondition(condition(), description)
  }
  static func settle() { RunLoop.main.run(until: Date().addingTimeInterval(0.15)) }
  static func main() {
    let folder = FileManager.default.temporaryDirectory.appendingPathComponent(
      "ms-clipboard-test-\(UUID().uuidString)")
    defer { try? FileManager.default.removeItem(at: folder) }
    let pb = NSPasteboard(name: .init("ms-clipboard-test-\(UUID().uuidString)"))
    defer { pb.releaseGlobally() }
    let history = ClipboardHistory(pasteboard: pb, directory: folder)
    history.start()
    wait("loaded") { history.loaded }
    func text(_ value: String, marker: NSPasteboard.PasteboardType? = nil) {
      pb.clearContents()
      let item = NSPasteboardItem()
      item.setString(value, forType: .string)
      if let marker { item.setString("1", forType: marker) }
      pb.writeObjects([item])
      history.poll()
    }
    text("alpha pin")
    wait("text capture") { history.entries.count == 1 }
    let pinnedID = history.entries[0].id
    history.togglePin(pinnedID)
    for marker in ClipboardHistory.ignoredTypes { text("must never persist", marker: marker) }
    settle()
    precondition(history.entries.count == 1)
    print("PASS concealed/transient/autogenerated/1Password/self filters")
    text("beta")
    wait("second text") { history.entries.count == 2 }
    text("alpha pin")
    wait("dedup") { history.entries.first?.id == pinnedID }
    precondition(history.entries.count == 2 && history.entries[0].pinned)
    let attributed = NSAttributedString(string: "rich text")
    let rtf = attributed.rtf(
      from: NSRange(location: 0, length: attributed.length), documentAttributes: [:])!
    pb.clearContents()
    pb.setString("rich text", forType: .string)
    pb.setData(rtf, forType: .rtf)
    history.poll()
    wait("RTF") { history.entries.first?.text == "rich text" }
    precondition(history.entries[0].rtf == rtf)
    var copied = false
    history.copy(history.entries[0]) { copied = $0 }
    wait("copy") { copied }
    history.poll()
    settle()
    precondition(history.entries.count == 3 && pb.data(forType: .rtf) == rtf)
    print("PASS dedup preserves pins, RTF retained, own copy skipped")
    pb.clearContents()
    let urls = [
      URL(fileURLWithPath: "/private/tmp/one.txt"), URL(fileURLWithPath: "/private/tmp/two.txt"),
    ]
    pb.writeObjects(urls as [NSURL])
    history.poll()
    wait("files") { history.entries.first?.kind == .files }
    precondition(history.entries[0].fileURLs?.count == 2)
    print("PASS multiple file URLs")
    for index in 0..<305 { text("entry-\(index)") }
    wait("eviction") { history.entries.first?.text == "entry-304" }
    precondition(
      history.entries.count == 300 && history.entries.contains { $0.id == pinnedID && $0.pinned })
    print("PASS 300-entry cap keeps pinned oldest entry")
    for index in 0..<52 {
      let rep = NSBitmapImageRep(
        bitmapDataPlanes: nil, pixelsWide: index == 0 ? 3000 : 32,
        pixelsHigh: 24, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
        isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
      memset(rep.bitmapData!, Int32(index + 100), rep.bytesPerRow * rep.pixelsHigh)
      let png = rep.representation(using: .png, properties: [:])!
      let previousID = history.entries.first?.id
      pb.clearContents()
      pb.setData(png, forType: .png)
      if index == 0 { pb.setString("Image with secondary URL text", forType: .string) }
      history.poll()
      wait("image capture \(index)") {
        history.entries.first?.kind == .image && history.entries.first?.id != previousID
      }
      settle()
      if index == 0 {
        var imageCopied = false
        history.copy(history.entries[0]) { imageCopied = $0 }
        wait("image copy") { imageCopied }
        let source = CGImageSourceCreateWithData(pb.data(forType: .png)! as CFData, nil)!
        let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil)! as NSDictionary
        let width = properties[kCGImagePropertyPixelWidth] as! Int
        let height = properties[kCGImagePropertyPixelHeight] as! Int
        precondition(width <= 2048 && height <= 2048 && pb.data(forType: .tiff) != nil)
        print("PASS image resized to \(width)×\(height), PNG+TIFF paste")
      }
    }
    wait("50 images") { history.entries.filter { $0.kind == .image }.count == 50 }
    precondition(history.entries.count == 300)
    history.stop()
    let persisted = history.entries
    let pngCount = (try! FileManager.default.contentsOfDirectory(atPath: folder.path)).filter {
      $0.hasSuffix(".png")
    }.count
    precondition(pngCount == 50)
    let restored = ClipboardHistory(pasteboard: pb, directory: folder)
    restored.start()
    wait("restore") { restored.loaded }
    precondition(restored.entries == persisted)
    restored.clearUnpinned()
    precondition(restored.entries.count == 1 && restored.entries[0].id == pinnedID)
    restored.stop()
    let remainingPNG = (try! FileManager.default.contentsOfDirectory(atPath: folder.path)).filter {
      $0.hasSuffix(".png")
    }.count
    precondition(remainingPNG == 0)
    precondition(
      ClipboardPanel.matches("apn", in: "alpha pin")
        && !ClipboardPanel.matches("zzz", in: "alpha pin"))
    print(
      "PASS 50-image cap, persistence/reload equality, clear preserves pins and removes image files, fuzzy search"
    )
  }
}
